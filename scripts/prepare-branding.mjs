import { copyFile, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { load } from "js-yaml";
import sharp from "sharp";
import { loadBranding, runtimeBranding } from "./branding-config.mjs";
import { buildBrandIcons, buildTrayIco } from "./build-brand-icon.mjs";

export function createBrandBuilderConfig(base, brand, preview = false) {
  const config = structuredClone(base);
  config.productName = brand.displayName;
  config.executableName = "Piora";
  config.extraMetadata = { ...config.extraMetadata, productName: brand.displayName, desktopName: brand.displayName };
  config.win.icon = "../.branding/resources/icon.ico";
  config.linux.icon = "../.branding/resources/icon.png";
  config.linux.artifactName = `${brand.artifactPrefix}-\${version}-linux-x64-portable.\${ext}`;
  config.nsis.shortcutName = brand.displayName;
  config.nsis.uninstallDisplayName = brand.displayName;
  config.nsis.artifactName = `${brand.artifactPrefix}-\${version}-win-x64-setup.\${ext}`;
  config.portable.artifactName = `${brand.artifactPrefix}-\${version}-win-x64-portable.\${ext}`;
  if (brand.assets.portableSplash) config.portable.splashImage = "../.branding/resources/portable-splash.bmp";
  else delete config.portable.splashImage;
  config.extraResources = config.extraResources.map(entry => {
    if (entry.to === "startup") return { from: "../.branding/resources/startup", to: "startup" };
    if (entry.to === "tray-icon.ico") return { from: "../.branding/resources/tray.ico", to: entry.to };
    if (entry.to === "tray-icon.png") return { from: "../.branding/resources/tray.png", to: entry.to };
    return entry;
  });
  config.extraResources.push({ from: "../.branding/runtime.json", to: "brand.json" });
  config.publish = { ...config.publish, ...brand.repository, releaseType: preview ? "prerelease" : "release",
    channel: brand.updateChannels[preview ? "preview" : "stable"] };
  return config;
}

export async function prepareBranding(projectRoot = resolve(import.meta.dirname, ".."), requestedBrand) {
  const brand = await loadBranding(projectRoot, requestedBrand);
  // Validate before changing generated files. sharp also detects malformed SVG/PNG/JPEG.
  await sharp(brand.assets.icon).metadata();
  for (const key of ["trayIcon", "startupPoster"]) if (brand.assets[key]) await sharp(brand.assets[key]).metadata();
  const generatedRoot = resolve(projectRoot, ".branding");
  const resources = resolve(generatedRoot, "resources");
  await mkdir(resources, { recursive: true });
  const startup = resolve(resources, "startup");
  // Only remove known generated filenames within this workspace's .branding directory.
  await mkdir(startup, { recursive: true });
  for (const name of ["polaris-rover.mp4", "polaris-rover.jpg", "icon.png"]) await rm(resolve(startup, name), { force: true });
  await rm(resolve(resources, "portable-splash.bmp"), { force: true });
  await buildBrandIcons(projectRoot, brand.assets.icon, ".branding/resources");
  const offlineTemplate = await readFile(resolve(projectRoot, "branding/offline.template.html"), "utf8");
  const htmlName = brand.displayName.replace(/[&<>"']/g, character => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[character]);
  await writeFile(resolve(projectRoot, "public/offline.html"), offlineTemplate.replaceAll("{{APP_DISPLAY_NAME}}", htmlName));
  await copyFile(brand.assets.trayIcon ?? resolve(resources, "icon.png"), resolve(resources, "tray.png"));
  if (brand.assets.trayIcon) await buildTrayIco(brand.assets.trayIcon, resolve(resources, "tray.ico"));
  else await copyFile(resolve(resources, "icon.ico"), resolve(resources, "tray.ico"));
  await copyFile(resolve(resources, "icon.png"), resolve(startup, "icon.png"));
  for (const [key, destination] of [["startupVideo", "startup/polaris-rover.mp4"], ["startupPoster", "startup/polaris-rover.jpg"], ["portableSplash", "portable-splash.bmp"]]) {
    if (brand.assets[key]) await copyFile(brand.assets[key], resolve(resources, destination));
  }
  const runtime = runtimeBranding(brand);
  const source = `// Generated by scripts/prepare-branding.mjs; do not edit.\nexport const APP_BRAND = ${JSON.stringify(runtime, null, 2)} as const;\nexport const APP_DISPLAY_NAME: string = APP_BRAND.displayName;\n`;
  for (const target of ["lib/generated/brand.ts", "desktop/src/generated/brand.ts"]) {
    const file = resolve(projectRoot, target);
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, source);
  }
  await writeFile(resolve(generatedRoot, "runtime.json"), JSON.stringify(runtime, null, 2) + "\n");
  const base = load(await readFile(resolve(projectRoot, "desktop/electron-builder.yml"), "utf8"));
  for (const preview of [false, true]) {
    const config = createBrandBuilderConfig(base, brand, preview);
    await writeFile(resolve(generatedRoot, preview ? "builder-preview.json" : "builder.json"), JSON.stringify(config, null, 2) + "\n");
  }
  return runtime;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  prepareBranding().then(brand => console.log(`Prepared ${brand.displayName} (${brand.id})`)).catch(error => { console.error(error); process.exitCode = 1; });
}
