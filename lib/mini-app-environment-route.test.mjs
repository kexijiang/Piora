import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {resolve,join,dirname} from 'node:path';
import {createJiti} from 'jiti';
import {prepareMiniAppRuntime} from '../scripts/prepare-mini-app-runtime.mjs';
const jiti=createJiti(import.meta.url,{alias:{'@':resolve(import.meta.dirname,'..')}});
const {GET,POST}=await jiti.import('../app/api/mini-app/environment/route.ts');
const {writeBetaFeatures}=await jiti.import('./beta-features.ts');
const {miniAppEnvironments}=await jiti.import('./mini-app/environment-store.ts');
const {MINI_APP_RENDERER_PROTOCOL}=await jiti.import('./mini-app/environment-protocol.ts');
await prepareMiniAppRuntime();

test('environment API checks origin, body bounds, version and Beta state and accepts revocation after disable',async t=>{
  const root=mkdtempSync(join(tmpdir(),'piora-env-api-')),previous=process.env.PI_CODING_AGENT_DIR;process.env.PI_CODING_AGENT_DIR=root;
  t.after(()=>{if(previous===undefined)delete process.env.PI_CODING_AGENT_DIR;else process.env.PI_CODING_AGENT_DIR=previous;assert.equal(dirname(root),tmpdir());rmSync(root,{recursive:true,force:true});});
  const url='http://127.0.0.1:30141/api/mini-app/environment',headers={host:'127.0.0.1:30141',origin:'http://127.0.0.1:30141','content-type':'application/json'};
  const post=(body,extra={})=>POST(new Request(url,{method:'POST',headers:{...headers,...extra},body:typeof body==='string'?body:JSON.stringify(body)}));
  writeBetaFeatures({intelligentUi:true},root);
  const config=await (await GET(new Request(url,{headers}))).json();assert.equal(config.enabled,true);assert.equal(config.protocol,MINI_APP_RENDERER_PROTOCOL);assert.match(config.rendererDigest,/^[a-f0-9]{64}$/);
  const report={protocol:config.protocol,rendererDigest:config.rendererDigest,webgl:true,instance:'route-window-12345678',epoch:1,sequence:1};
  const body={action:'prepare',report,sessionId:'route-session',submissionId:'route-submission'};
  assert.equal((await post(body,{origin:'https://outside.invalid'})).status,403);assert.equal((await post('x'.repeat(4001))).status,409);
  assert.equal((await post({...body,report:{...report,protocol:'old'}})).status,409);
  assert.equal((await post(body)).status,200);
  const run={runId:'route-run',sessionId:'route-session',source:'ui',submissionId:'route-submission'};miniAppEnvironments().bind(run);assert.equal(miniAppEnvironments().webgl(run,config.rendererDigest),true);
  writeBetaFeatures({intelligentUi:false},root);assert.equal((await post({...body,report:{...report,sequence:2}})).status,409);
  assert.equal((await post({action:'revoke',report:{...report,epoch:2,sequence:3,webgl:false}})).status,200);assert.equal(miniAppEnvironments().webgl(run,config.rendererDigest),false);miniAppEnvironments().release(run);
});
