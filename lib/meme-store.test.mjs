import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { createJiti } from "jiti";
import sharp from "sharp";
const jiti = createJiti(import.meta.url);
const { captureMeme, readMemeImage } = await jiti.import("./meme-store.ts");
test("immutable image receipts validate bytes and paths, deduplicate, and survive a stopped plugin", async t => {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), "piora-meme-receipt-"));
  const previous = { dir: process.env.PI_CODING_AGENT_DIR, ipc: process.env.PIORA_DESKTOP_NETWORK_IPC, send: process.send, connected: process.connected };
  t.after(() => { process.send = previous.send; process.connected = previous.connected;
    for (const [key, value] of [["PI_CODING_AGENT_DIR", previous.dir], ["PIORA_DESKTOP_NETWORK_IPC", previous.ipc]]) { if (value === undefined) delete process.env[key]; else process.env[key] = value; }
    fs.rmSync(temp, { recursive: true, force: true }); });
  process.env.PI_CODING_AGENT_DIR = temp; process.env.PIORA_DESKTOP_NETWORK_IPC = "1"; process.connected = true;
  let bytes = await sharp({ create: { width: 8, height: 8, channels: 4, background: "red" } }).png().toBuffer();
  const original = bytes;
  process.send = (message, callback) => { queueMicrotask(() => process.emit("message", { type: "pi-desktop:meme-response", requestId: message.requestId, ok: true, value: { status: 200, mime: "image/png", data: bytes.toString("base64") } })); callback?.(); return true; };
  const markdown = await captureMeme("/dsh-memes/fixture/memes/happy/a.png", "hello]\n<script>");
  assert.doesNotMatch(markdown, /<script>/);
  const id = markdown.match(/\/api\/memes\/([a-f0-9]{64})/)[1];
  assert.deepEqual(readMemeImage(id).bytes, original);
  assert.equal((await captureMeme("/dsh-memes/fixture/memes/happy/a.png", "again")).includes(id), true);
  await assert.rejects(captureMeme("/dsh-memes/../secret", "bad"), /Invalid/);
  await assert.rejects(captureMeme("https://evil.invalid/image", "bad"), /Invalid/);
  assert.throws(() => readMemeImage("../catalog.json"), /Invalid/);
  bytes = Buffer.from("<svg/>"); await assert.rejects(captureMeme("/dsh-memes/fixture/bad.png", "bad"));
  bytes = Buffer.alloc(8 * 1024 * 1024 + 1); await assert.rejects(captureMeme("/dsh-memes/fixture/big.png", "big"), /too large/);
  process.connected = false;
  assert.deepEqual(readMemeImage(id).bytes, original);
});
