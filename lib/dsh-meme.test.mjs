import assert from "node:assert/strict";
import test from "node:test";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createJiti } from "jiti";
const jiti = createJiti(import.meta.url);
const { memeNetwork, prepareMemeRuntime, DSH_MEME_VERSION, DSH_MEME_INTEGRITY } = await jiti.import("../desktop/src/dsh-meme-install.ts");
const { petEnvironment, verifyDownload } = await jiti.import("../desktop/src/dsh-pet-install.ts");
test("pinned meme installation shares proxy and CA policy while isolating registry overrides and credentials", () => {
  assert.equal(DSH_MEME_VERSION, "0.1.76"); assert.throws(() => verifyDownload(Buffer.from("tampered"), DSH_MEME_INTEGRITY));
  const source = { PIORA_DSH_MEME_REGISTRY: "https://meme.invalid/npm/", PIORA_DSH_PET_REGISTRY: "https://pet.invalid/", NPM_CONFIG_REGISTRY: "https://npm.invalid/", HTTPS_PROXY: "http://user:pass@proxy.invalid:8080", NODE_EXTRA_CA_CERTS: "extra.pem", npm_config_cafile: "npm.pem", OPENAI_API_KEY: "secret", NODE_OPTIONS: "--require unwanted.js" };
  const network = memeNetwork(source);
  assert.equal(network.registry, "https://meme.invalid/npm/");
  assert.equal(network.environment.HTTPS_PROXY, source.HTTPS_PROXY);
  assert.equal(network.environment.NPM_CONFIG_CAFILE, "npm.pem"); assert.equal(network.environment.NODE_EXTRA_CA_CERTS, "extra.pem");
  const child = petEnvironment("fixture", source, network);
  assert.equal(child.OPENAI_API_KEY, undefined); assert.equal(child.NODE_OPTIONS, undefined); assert.equal(child.NODE_TLS_REJECT_UNAUTHORIZED, undefined);
  assert.equal(memeNetwork({ PIORA_DSH_PET_REGISTRY: "https://pet.invalid/", NPM_CONFIG_REGISTRY: "https://npm.invalid/" }).registry, "https://npm.invalid/");
  assert.equal(memeNetwork(source, { mode: "direct", proxyUrl: "", bypass: "" }).environment.HTTPS_PROXY, "");
  assert.equal(memeNetwork(source, { mode: "manual", proxyUrl: "http://manual.invalid:123", bypass: "internal" }).environment.HTTPS_PROXY, "http://manual.invalid:123");
  assert.throws(() => memeNetwork({ PIORA_DSH_MEME_REGISTRY: "https://token@mirror.invalid/" }));
});
test("bundled index adaptation is pinned, idempotent, and preserves edits across program reinstall", async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "piora-meme-adapter-"));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const pkg = path.join(root, "installed", "node_modules", "dsh-meme");
  fs.mkdirSync(path.join(pkg, "memes"), { recursive: true }); fs.writeFileSync(path.join(pkg, "memes", "index.db"), "original");
  const source = "export function bundledPacksDir() { return fileURLToPath(new URL('./memes', import.meta.url)) }";
  fs.writeFileSync(path.join(pkg, "memes.js"), source);
  await prepareMemeRuntime(root);
  const adapted = fs.readFileSync(path.join(pkg, "memes.js"), "utf8"); assert.match(adapted, /persistent bundled library/);
  const data = path.join(root, "home", "bundled-memes", "index.db"); fs.writeFileSync(data, "edited");
  await prepareMemeRuntime(root); assert.equal(fs.readFileSync(data, "utf8"), "edited");
  fs.writeFileSync(path.join(pkg, "memes.js"), source); await prepareMemeRuntime(root); assert.equal(fs.readFileSync(data, "utf8"), "edited");
  fs.writeFileSync(path.join(pkg, "memes.js"), "changed upstream layout"); await assert.rejects(prepareMemeRuntime(root), /Unsupported/);
});
